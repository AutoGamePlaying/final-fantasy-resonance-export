/// Default UE `MovieScene.TickResolution` numerator when omitted.
const DEFAULT_TICK_RESOLUTION: i64 = 24_000;
/// Default UE `MovieScene.DisplayRate` numerator when omitted.
const DEFAULT_DISPLAY_RATE: i64 = 30;
/// All-zero UE `FGuid` representing an absent parent binding.
const ZERO_GUID: &str = "00000000-00000000-00000000-00000000";
/// Prefix generated by UE5 Sequencer for Director Blueprint event entrypoint stubs.
const ENTRYPOINT_PREFIX: &str = "SequenceEvent__ENTRYPOINT";
/// Prefix of UE Blueprint compiled Ubergraph functions.
const UBERGRAPH_PREFIX: &str = "ExecuteUbergraph_";

/// All property keys known to hold section object references across UE `MovieSceneTrack` types.
const TRACK_SECTION_ARRAY_KEYS: &[&str] = &[
    "Sections",
    "ConstraintSections",
    "AtomSections",
    "CameraShakeSections",
    "ManaSections",
    "ParticleSections",
    "AnimationSections",
];

/// High-level category of a `LevelSequence` asset inferred from its UE content path.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SequenceCategory {
    Battle,
    Event,
    Other,
}

impl SequenceCategory {
    /// Canonical lowercase string stored in `sequence.category`.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Battle => "battle",
            Self::Event => "event",
            Self::Other => "other",
        }
    }

    /// Infer category from a canonical UE package path or relative Sequencer path.
    pub fn from_path(path: &str) -> Self {
        let lower = path.to_ascii_lowercase();
        if lower.contains("/sequencer/battle/") || lower.starts_with("battle/") {
            Self::Battle
        } else if lower.contains("/sequencer/event/") || lower.starts_with("event/") {
            Self::Event
        } else {
            Self::Other
        }
    }
}

/// Rational frame rate (`numerator / denominator`), matching UE `FFrameRate`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct FrameRate {
    pub numerator: i64,
    pub denominator: i64,
}

impl FrameRate {
    /// Frames (or ticks) per second as `f64`.
    pub fn as_fps(self) -> f64 {
        if self.denominator == 0 {
            0.0
        } else {
            self.numerator as f64 / self.denominator as f64
        }
    }
}

