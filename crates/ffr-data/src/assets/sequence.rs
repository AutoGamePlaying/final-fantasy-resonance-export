//! Cutscene `LevelSequence` metadata, binding, track, and event trigger types and parser.
//!
//! Parses CUE4Parse JSON exports under `FFRS/Content/Sequencer/**/*.json` into typed Rust objects
//! backing `sequence`, `sequence_binding`, `sequence_track`, and `sequence_event` in the
//! `09_sequences` database area.

