/// Top-level `LevelSequence` descriptor serialized into `sequence.doc`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Sequence {
    /// Canonical UE package path, e.g. `/Game/Sequencer/Event/Main_Event/C01/.../SEQ_...`.
    pub path: String,
    /// Asset name, e.g. `SEQ_Ev_C01_001A_01_MasterSequencer`.
    pub name: String,
    /// Directory prefix (everything before the last `/`).
    pub dir: String,
    pub category: SequenceCategory,
    /// Display rate (`MovieScene.DisplayRate`, typically 30/1).
    pub display_rate: FrameRate,
    /// Internal tick resolution (`MovieScene.TickResolution`, typically 24000/1).
    pub tick_resolution: FrameRate,
    /// Playback start in internal ticks, if `PlaybackRange` has a closed lower bound.
    pub start_ticks: Option<i64>,
    /// Playback end in internal ticks, if `PlaybackRange` has a closed upper bound.
    pub end_ticks: Option<i64>,
    /// Playback start in display frames.
    pub start_frame: Option<f64>,
    /// Playback end in display frames.
    pub end_frame: Option<f64>,
    /// Playback start in seconds.
    pub start_secs: Option<f64>,
    /// Playback end in seconds.
    pub end_secs: Option<f64>,
    /// Playback duration in seconds (`end_secs - start_secs`, or `0.0` when unbounded/absent).
    pub duration_secs: f64,
    pub binding_count: u32,
    pub track_count: u32,
    pub event_count: u32,
    /// Director Blueprint generated class name (e.g. `SEQ_..._DirectorBP_C`), if present.
    pub director_class: Option<String>,
    /// Parent class of the Director Blueprint (e.g. `CPP_TalkEventSequenceDirector`).
    pub director_super_class: Option<String>,
    /// Named markers on `MovieScene.MarkedFrames`.
    #[serde(default)]
    pub marked_frames: Vec<SequenceMarkedFrame>,
    /// Whether `MarkedFrames` includes skip range markers (`SkipBegin` / `SkipEnd`).
    pub has_skip_markers: bool,
    /// Whether Director Blueprint declares a skip-ban parameter (`InIsBanSkip` / `InIsBanTalkSkip`).
    pub has_skip_ban_param: bool,
    /// Referenced sub-sequence package paths from `MovieSceneSubSection` / `MovieSceneCinematicShotSection`.
    #[serde(default)]
    pub sub_sequences: Vec<String>,
    /// Custom functions declared on the Director Blueprint (excluding ENTRYPOINT stubs and Ubergraph).
    #[serde(default)]
    pub director_functions: Vec<DirectorFunction>,
    /// Blueprint/C++ function names invoked inside `ExecuteUbergraph` (from `CallFunc_*` locals).
    #[serde(default)]
    pub ubergraph_calls: Vec<String>,
}

