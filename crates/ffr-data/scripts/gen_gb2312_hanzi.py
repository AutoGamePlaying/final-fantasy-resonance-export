#!/usr/bin/env python3
"""Generate `crates/ffr-data/src/gb2312_hanzi.rs` from Python's stdlib `gb2312` codec.

Enumerates every valid two-byte code in the GB2312 Hanzi area (0xB0A1..=0xF7FE) and emits a
sorted `u32` Unicode code-point table suitable for binary search.
"""

from __future__ import annotations

from pathlib import Path

EXPECTED_COUNT = 6763
ITEMS_PER_LINE = 12
SCRIPT_REL_PATH = "crates/ffr-data/scripts/gen_gb2312_hanzi.py"


def collect_gb2312_hanzi() -> list[int]:
    codepoints: set[int] = set()
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if len(ch) == 1:
                codepoints.add(ord(ch))
    result = sorted(codepoints)
    if len(result) != EXPECTED_COUNT:
        raise RuntimeError(
            f"Expected {EXPECTED_COUNT} GB2312 Hanzi code points, got {len(result)}"
        )
    return result


def render_rust(codepoints: list[int]) -> str:
    lines = [
        f"// @generated by `{SCRIPT_REL_PATH}` from Python stdlib `gb2312` codec (0xB0A1..=0xF7FE).",
        "// Do not edit manually; re-run the script to regenerate.",
        "",
        "//! Sorted Unicode scalar table for the 6,763 Simplified Chinese Hanzi in GB2312.",
        "",
        "/// Sorted Unicode code points (`u32`) for all 6,763 Hanzi encoded in GB2312 (`0xB0A1..=0xF7FE`).",
        f"pub static GB2312_HANZI: [u32; {len(codepoints)}] = [",
    ]
    for i in range(0, len(codepoints), ITEMS_PER_LINE):
        chunk = codepoints[i : i + ITEMS_PER_LINE]
        formatted = ", ".join(f"0x{cp:04X}" for cp in chunk)
        lines.append(f"    {formatted},")
    lines.extend(
        [
            "];",
            "",
            "/// Returns `true` when `ch` belongs to the 6,763 GB2312 Simplified Chinese Hanzi set.",
            "pub fn is_gb2312_hanzi(ch: char) -> bool {",
            "    GB2312_HANZI.binary_search(&(ch as u32)).is_ok()",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[3]
    out_path = repo_root / "crates" / "ffr-data" / "src" / "gb2312_hanzi.rs"
    codepoints = collect_gb2312_hanzi()
    out_path.write_text(render_rust(codepoints), encoding="utf-8", newline="\n")
    print(f"Wrote {len(codepoints)} code points to {out_path}")


if __name__ == "__main__":
    main()
